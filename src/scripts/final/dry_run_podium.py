def say(s=""):
    print(s, flush=True)
    out.append(s)


def sha(p):
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for b in iter(lambda: f.read(1 << 20), b""):
            h.update(b)
    return h.hexdigest()


def parse_text(t):
    return dict(re.findall(r"(\w+)=('[^']*'|\[[^\]]*\]|<[^>]*>|[^,)]+)", t))


def norm(v):
    if v is None:
        return None
    m = re.fullmatch(r"<\w+\.(\w+): [^>]*>", v)
    return (m.group(1) if m else v.strip("'")).lower()


def job_words(text):
    body = text.split("-m src.patchECG_finetune")[1].split("\n\n")[0].replace("\\\n", " ")
    return shlex.split(body.replace('"${STAGED_ROOT}"', "/tmp/none"))


def job_data(text):
    return re.search(r'\[\[ -f "([^"]+)/PatientSegmentRegressionDataset\.h5" \]\]', text).group(1)


def joblog(run):
    return dict(re.findall(r"^(\w+): (.*)$", (SAVE / run / "job_log.txt").read_text(), re.M))


def parse_all(texts):
    code = ("import sys, json; batch = json.loads(sys.stdin.read()); out = []\n"
            "for words in batch:\n"
            "    sys.argv = ['x'] + words\n"
            "    if 'src.patchECG_finetune' in sys.modules: del sys.modules['src.patchECG_finetune']\n"
            "    import src.patchECG_finetune as F\n"
            "    out.append(repr(F.args))\n"
            "print('ARGS ' + json.dumps(out))\n")
    res = subprocess.run([str(REPO / ".venv/bin/python"), "-c", code], input=json.dumps([job_words(t) for t in texts]), capture_output=True, text=True, cwd=REPO, timeout=1800)
    line = next((x for x in res.stdout.splitlines() if x.startswith("ARGS ")), None)
    assert line, res.stderr[-2000:]
    return [parse_text(a) for a in json.loads(line[5:])]


def flag_diff(got, ref):
    got = dict(got, dset=got.get("dset", got["dset_finetune"]))
    return {k: (ref.get(k), got.get(k)) for k in sorted(set(ref) | set(got)) if norm(ref.get(k)) != norm(got.get(k))}


def text_change(body, name, twin_name, k, twin):
    back = body.replace(name, twin_name).replace(f"/cv5_optB_fold{k:02d}", f"/cv5_optB_leadV2_opt2p_fold{k:02d}")
    d = difflib.unified_diff(twin.splitlines(), back.splitlines(), lineterm="", n=0)
    return [x for x in d if x[:1] in "+-" and not x.startswith(("+++", "---"))]


def loader(root, mode):
    p = Namespace(dset="patient-segment-regression", root_path=str(root), min_class_size=1, top_n_classes=None, classification_type=ClassificationType.REGRESSION,
                  custom_lead_selection=LEAD[mode], focal_loss=False, focal_alpha=None, regression_loss="mse", alt_lead_ordering=False, trafos=["None"],
                  batch_size=128, num_workers=0, reset_strat_folds=False, distributed=False)
    return get_dls(p)


jobs = pd.read_csv(GEN / "jobs.csv")
commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=REPO, capture_output=True, text=True).stdout.strip()
say(f"# Podium retraining: dry run ({datetime.now():%Y-%m-%d %H:%M}, VM)")
say()
say(f"Podium-only exception (`docs/DECISIONS.md` 2026-11-24). Generator `src/scripts/final/build_podium_sbatches.py`, this check "
    f"`src/scripts/final/dry_run_podium.py`; commit `{commit}` plus the uncommitted podium files. Nothing trained or submitted.")
assert len(jobs) == 6 and jobs.run_id.is_unique

# ---------------------------------------------------------------- 1. job list
