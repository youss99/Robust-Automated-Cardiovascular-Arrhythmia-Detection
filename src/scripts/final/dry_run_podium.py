"""Dry run for the podium-only retraining (docs/DECISIONS.md 2026-11-24): the 6 jobs written by build_podium_sbatches.py. No training, nothing submitted.

1. Job list, and the reused runs for folds 2 and 3.
2. Job text vs the FIN twin (regenerated by build_final_sbatches.py into a temporary folder): with the run ID and data folder put back, the only
   changed line is the backbone sha256 guard. Every flag through the real parser of src/patchECG_finetune.py vs the twin's params.txt (written on
   Narval): allowed differences model_name, save_path, root_path (per-job scratch). Data folder: from the job text (it is not a trainer flag).
3. Data: CSV sha256 = phase1_folds/SHA256SUMS.txt, H5 sha256 = SHA256SUMS.txt; the CSV split = the published manifests
   (ptbxl_models_v2/cv5_optB_fold_manifests); the real get_dls per fold and lead: records, windows, label mean and SD per split; gold-standard
   episodes per lead in each validation set; excluded record-lead pairs per split. Reused folds 2 and 3: the FIN S1 job_log.txt dataset, CSV sha
   and backbone sha.
4. check_training_paths.py (self-test).  5. sha256 of jobs.csv.  6. Fault injection.  7. Time estimate from the twins.
Usage: <repo>/.venv/bin/python src/scripts/final/dry_run_podium.py <generated folder (FIN_OUT_POD)> <output .md>"""
