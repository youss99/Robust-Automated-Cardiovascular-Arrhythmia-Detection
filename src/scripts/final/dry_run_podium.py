say("Reused for folds 2 and 3 (already on the published folders): FIN_L1_lead_II_S1_fold02, _fold03, FIN_L1_lead_V2_S1_fold02, _fold03.")

# ---------------------------------------------------------------- 2. text and flags vs twin
say()
say("## 2. Job vs FIN twin")
tmp = Path(tempfile.mkdtemp(prefix="pod_fin_"))
r = subprocess.run([sys.executable, str(REPO / "src/scripts/custom_dataset/build_final_sbatches.py")], env=dict(os.environ, FIN_OUT=str(tmp)), capture_output=True, text=True)
assert r.returncode == 0, r.stderr
fin_sha = sha(tmp / "jobs.csv")
ok_fin = fin_sha == "2133e92037d6c52239f4357d3b81b1440c8a88815d45bfb14f688895835480f8"
texts, twins, bad_text = {}, {}, []
for j in jobs.itertuples():
    texts[j.run_id] = (GEN / j.group / f"{j.run_id}.sbatch").read_text()
    twins[j.run_id] = (tmp / "step2_L1" / f"{j.twin}.sbatch").read_text()
    ch = text_change(texts[j.run_id], j.run_id, j.twin, j.fold, twins[j.run_id])
    if not (len(ch) == 1 and ch[0].startswith("+[[ \"$(sha256sum") and BB_SHA[j.mode] in ch[0]):
        bad_text.append((j.run_id, ch))
say()
say(f"Thesis generator unchanged (re-run into a temporary folder: jobs.csv sha256 `{fin_sha[:16]}…`, approved `2133e920…`): **{'PASS' if ok_fin else 'FAIL'}**.")
say(f"Job text, with run ID and data folder put back, differs from the twin only by the backbone sha256 guard line: **{6 - len(bad_text)} of 6 PASS**"
    + (f"; failures: {bad_text}" if bad_text else "."))
parsed = parse_all([texts[j.run_id] for j in jobs.itertuples()])
say()
say("| job | trainer flags that differ from the twin's params.txt | data folder (job text): twin → job |")
say("|---|---|---|")
bad_flags = []
for j, got in zip(jobs.itertuples(), parsed):
    ref = parse_text((SAVE / j.twin / "params.txt").read_text())
    d = flag_diff(got, ref)
    extra = set(d) - ALLOWED
    seed_ok = got["seed"] == ref["seed"] == str(j.seed)
    bb_ok = norm(got["pretrained_model_path"]) == norm(ref["pretrained_model_path"]) and norm(got["pretrained_model_path"]).endswith(f"{Path(j.backbone).name}".lower())
    if extra or not seed_ok or not bb_ok:
        bad_flags.append((j.run_id, extra, seed_ok, bb_ok))
    say(f"| {j.run_id} | {', '.join(f'{k}: {norm(v[0])} → {norm(v[1])}' for k, v in d.items())} | `{Path(joblog(j.twin)['dataset']).name}` → `{Path(job_data(texts[j.run_id])).name}` |")
say()
say(f"{len(parsed[0])} trainer values compared per job (defaults included). Only model_name, save_path and root_path (Narval scratch) may differ; seed and "
    f"backbone must equal the twin's: **{6 - len(bad_flags)} of 6 PASS**" + (f"; failures: {bad_flags}" if bad_flags else "."))

# ---------------------------------------------------------------- 3. data
say()
say("## 3. Data and loader")
sums = {ln.split("  ")[1]: ln.split("  ")[0] for ln in (FOLDS / "SHA256SUMS.txt").read_text().splitlines() if ln.strip()}
h5s = {sha(FOLDS / f"cv5_optB_fold{k:02d}" / H5) if k == 1 else None for k in [1]}
h5_ok = all(os.path.samefile(FOLDS / f"cv5_optB_fold{k:02d}" / H5, FOLDS / "cv5_optB_fold01" / H5) for k in range(1, 6)) and h5s == {sums[H5]}
gs = pd.read_csv(GS)
gs = gs[gs.record != "s20121"]
rows, data_ok = [], True
for k in range(1, 6):
    root = FOLDS / f"cv5_optB_fold{k:02d}"
    csv_sha = sha(root / CSV)
    full = pd.read_csv(root / CSV, usecols=["patient_id", "target_lead0_mV", "target_lead1_mV", "strat_fold_annotated"])
    man = pd.read_csv(MAN / f"fold{k:02d}.csv")
    man_split = dict(zip(man.patient_id, man.split.str.lower()))
    csv_split = {p: SPLIT[int(s)] for p, s in full[["patient_id", "strat_fold_annotated"]].drop_duplicates().itertuples(index=False)}
    ok = csv_sha == sums[f"cv5_optB_fold{k:02d}/{CSV}"] and csv_split == man_split
    for mode in LEAD:
        L = LEAD[mode]
        dl = loader(root, mode)
        for sp, d in (("train", dl.train), ("val", dl.valid), ("test", dl.test)):
            y = d.dataset.data_y
            recs = sorted(y.patient_id.unique())
            ok &= recs == sorted(p for p, s in man_split.items() if s == sp) and len(d.dataset) == int(full.patient_id.isin(recs).sum())
            lab = full.iloc[y.original_index.to_numpy()][TGT[L]]
            eps = int(((gs.lead_paper == L) & gs.record.isin(recs)).sum()) if sp == "val" else None
            rows.append(dict(fold=k, mode=mode, split=sp, records=len(recs), windows=len(d.dataset), mean=lab.mean(), sd=lab.std(), gs_eps=eps,
                             recs=" ".join(r[-5:] for r in recs), excluded=", ".join(f"{r[-5:]} {l}" for r in recs for l in ("II", "V2") if (r, l) in EXCL)))
    data_ok &= ok
    say(f"- fold {k}: `cv5_optB_fold{k:02d}` CSV sha256 `{csv_sha[:16]}…` = SHA256SUMS.txt, split column = published manifest, loader records = manifest: **{'PASS' if ok else 'FAIL'}**")
say(f"- H5: one file linked into all five folders, sha256 = SHA256SUMS.txt (`{sums[H5][:16]}…`): **{'PASS' if h5_ok else 'FAIL'}**")
for k in (2, 3):
    for mode in LEAD:
        lg = joblog(f"FIN_L1_{mode}_S1_fold{k:02d}")
        good = Path(lg["dataset"]).name == f"cv5_optB_fold{k:02d}" and lg["dataset_csv_sha256"] == sums[f"cv5_optB_fold{k:02d}/{CSV}"] and lg["backbone_sha256"] == BB_SHA[mode] and lg["seed"].strip() == str(200 + k - 1)
        data_ok &= good
        say(f"- reused FIN_L1_{mode}_S1_fold{k:02d}: job_log dataset `{Path(lg['dataset']).name}`, CSV sha = SHA256SUMS.txt, backbone sha `{lg['backbone_sha256'][:8]}…`, seed {lg['seed'].strip()}: **{'PASS' if good else 'FAIL'}**")
R = pd.DataFrame(rows)
R.to_csv(OUT_MD.with_name(OUT_MD.stem + "_loader.csv"), index=False)
say()
say("Loader (real `get_dls`), label = the model's own lead (mV). Excluded record–lead pairs keep their real labels in training and validation, as in the published runs.")
