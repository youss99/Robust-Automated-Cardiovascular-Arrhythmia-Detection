say(f"`check_training_paths.py`: **{m.group(0) if m else 'no summary line'}** (exit {st.returncode}): **{'PASS' if st_ok else 'FAIL'}**")

# ---------------------------------------------------------------- 6. fault injection
say()
say("## 5. The checks fail on injected faults")
j0 = jobs.iloc[0]
t0, tw0 = texts[j0.run_id], twins[j0.run_id]
ref0 = parse_text((SAVE / j0.twin / "params.txt").read_text())
faults = [("text: lr changed", text_change(t0.replace("--lr=0.001", "--lr=0.002"), j0.run_id, j0.twin, j0.fold, tw0) != text_change(t0, j0.run_id, j0.twin, j0.fold, tw0)),
          ("text: epochs 70 -> 90", text_change(t0.replace("--n_epochs_finetune=70", "--n_epochs_finetune=90"), j0.run_id, j0.twin, j0.fold, tw0) != text_change(t0, j0.run_id, j0.twin, j0.fold, tw0)),
          ("flags: weight_decay changed", bool(set(flag_diff(dict(parsed[0], weight_decay="0.0"), ref0)) - ALLOWED)),
          ("flags: seed changed", bool(set(flag_diff(dict(parsed[0], seed="201"), ref0)) - ALLOWED))]
for n, caught in faults:
    say(f"- {n}: {'flagged' if caught else 'NOT FLAGGED'}")
ok_faults = all(c for _, c in faults)

# ---------------------------------------------------------------- 7. time
say()
say("## 6. Time estimate")
