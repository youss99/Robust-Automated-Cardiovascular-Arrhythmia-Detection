say("|--:|---|---|--:|--:|---|--:|---|---|")
for r in R.itertuples():
    say(f"| {r.fold} | {r.mode} | {r.split} | {r.records} | {r.windows:,} | {r.mean:+.4f} ± {r.sd:.4f} | {'' if r.gs_eps is None or pd.isna(r.gs_eps) else int(r.gs_eps)} | {r.excluded} | {r.recs} |")

# ---------------------------------------------------------------- 4. self-test
